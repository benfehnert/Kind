/**
 * Downloads pravatar + scene URLs from mock-data/community.json → assets/images/
 * Then regenerate src/assets/imageManifest.js
 */
import fs from "fs";
import path from "path";
import { fileURLToPath } from "url";

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const mobileRoot = path.join(__dirname, "..");
const outDir = path.join(mobileRoot, "assets", "images");
const manifestPath = path.join(mobileRoot, "src", "assets", "imageManifest.js");

function collectPravatarIds() {
  const c = JSON.parse(fs.readFileSync(path.join(mobileRoot, "mock-data", "community.json"), "utf8"));
  const ids = new Set();
  const add = (u) => {
    if (u && u.img != null) ids.add(u.img);
  };
  if (c.commUsers) Object.values(c.commUsers).forEach(add);
  (c.basicUsers || []).forEach(add);
  (c.followerOnly || []).forEach(add);
  (c.researchers || []).forEach(add);
  [11, 22, 9, 28].forEach((n) => ids.add(n));
  return [...ids].sort((a, b) => a - b);
}

async function download(url, dest) {
  const res = await fetch(url, {
    redirect: "follow",
    headers: {
      "User-Agent": "Mozilla/5.0 (compatible; kind-prototype-assets/1.0)"
    }
  });
  if (!res.ok) throw new Error(`${res.status} ${url}`);
  const buf = Buffer.from(await res.arrayBuffer());
  fs.writeFileSync(dest, buf);
}

async function main() {
  fs.mkdirSync(outDir, { recursive: true });
  fs.mkdirSync(path.dirname(manifestPath), { recursive: true });

  const community = JSON.parse(fs.readFileSync(path.join(mobileRoot, "mock-data", "community.json"), "utf8"));
  const pravatarIds = collectPravatarIds();

  for (const id of pravatarIds) {
    const dest = path.join(outDir, `pravatar-${id}.jpg`);
    if (fs.existsSync(dest)) continue;
    const url = `https://i.pravatar.cc/512?img=${id}`;
    console.log("fetch", url);
    await download(url, dest);
  }

  for (const [key, url] of Object.entries(community.sceneAvatars || {})) {
    const dest = path.join(outDir, `scene-${key}.jpg`);
    if (fs.existsSync(dest)) continue;
    const picsum = `https://picsum.photos/seed/${encodeURIComponent(`kind-${key}`)}/512/512`;
    console.log("fetch scene", key, picsum, "(placeholder; original Unsplash blocked for automated fetch)");
    await download(picsum, dest);
  }

  const entries = [];
  for (const f of fs.readdirSync(outDir)) {
    if (!f.endsWith(".jpg")) continue;
    const key = f.replace(/\.jpg$/i, "");
    entries.push([key, f]);
  }
  entries.sort((a, b) => a[0].localeCompare(b[0]));

  const reqLines = entries.map(([key, file]) => {
    const reqPath = `../../assets/images/${file}`;
    return `  "${key.replace(/\\/g, "\\\\")}": require("${reqPath}"),`;
  });

  const header = `/* eslint-disable global-require */\n/* Auto-generated by scripts/download-prototype-assets.mjs */\n\n`;
  fs.writeFileSync(
    manifestPath,
    `${header}export const imageManifest = Object.freeze({\n${reqLines.join("\n")}\n});\n\nexport function resolveImageSource(key) {\n  if (!key) return null;\n  return imageManifest[key] ?? null;\n}\n`
  );

  console.log("Wrote", manifestPath, "with", entries.length, "entries");
}

main().catch((e) => {
  console.error(e);
  process.exit(1);
});
